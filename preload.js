// BV Mudrana: safe bridge between the window and the main process
const { contextBridge, ipcRenderer, webFrame } = require('electron');

contextBridge.exposeInMainWorld('native', {
  open: () => ipcRenderer.invoke('dialog:open'),
  openMany: (opts) => ipcRenderer.invoke('dialog:openMany', opts),
  openPath: (p) => ipcRenderer.invoke('open-path', p),
  readBvm: (p) => ipcRenderer.invoke('read-bvm', p),
  save: (opts) => ipcRenderer.invoke('dialog:save', opts),
  saveAsDialog: (opts) => ipcRenderer.invoke('dialog:saveAs', opts),
  writeBvm: (opts) => ipcRenderer.invoke('file:writeBvm', opts),
  saveText: (opts) => ipcRenderer.invoke('dialog:saveText', opts),
  exportFile: (opts) => ipcRenderer.invoke('dialog:exportFile', opts),
  chooseFolder: (opts) => ipcRenderer.invoke('dialog:chooseFolder', opts),
  choosePath: (opts) => ipcRenderer.invoke('dialog:choosePath', opts),
  writeMany: (opts) => ipcRenderer.invoke('file:writeMany', opts),
  copyFonts: (opts) => ipcRenderer.invoke('file:copyFonts', opts),
  place: (opts) => ipcRenderer.invoke('dialog:place', opts),
  docxParts: (p) => ipcRenderer.invoke('docx:parts', p),
  docxWrite: (o) => ipcRenderer.invoke('docx:write', o),
  legacyPickFile: () => ipcRenderer.invoke('legacy:pickFile'),
  legacySaveAs: (o) => ipcRenderer.invoke('legacy:saveAs', o),
  writeText: (o) => ipcRenderer.invoke('file:writeText', o),
  prajaFontsDir: () => ipcRenderer.invoke('praja:fontsDir'),
  userGet: () => ipcRenderer.invoke('user:get'),
  userSet: (name) => ipcRenderer.invoke('user:set', name),
  linkStatus: (links) => ipcRenderer.invoke('link:status', links),
  exportPdf: (opts) => ipcRenderer.invoke('export:pdf', opts),
  exportPdfTo: (opts) => ipcRenderer.invoke('export:pdf-to', opts),
  exportPng: (opts) => ipcRenderer.invoke('export:png', opts),
  print: (opts) => ipcRenderer.invoke('print', opts),
  fonts: () => ipcRenderer.invoke('fonts:list'),
  fontCss: (families) => ipcRenderer.invoke('fonts:css', families),
  menuFonts: (list) => ipcRenderer.send('menu-fonts', list),
  menuStyles: (list) => ipcRenderer.send('menu-styles', list),
  pmFind: () => ipcRenderer.invoke('pm:find'),
  pmLocate: () => ipcRenderer.invoke('pm:locate'),
  autosaveWrite: (o) => ipcRenderer.invoke('autosave:write', o),
  autosaveList: () => ipcRenderer.invoke('autosave:list'),
  autosaveRead: (id) => ipcRenderer.invoke('autosave:read', id),
  autosaveDelete: (id) => ipcRenderer.invoke('autosave:delete', id),
  pmSave: (job) => ipcRenderer.invoke('pm:save', job),
  onPmProgress: (fn) => ipcRenderer.on('pm-progress', (_e, m) => fn(m)),
  recent: () => ipcRenderer.invoke('recent:get'),
  addRecent: (p) => ipcRenderer.invoke('recent:add', p),
  clearRecent: () => ipcRenderer.invoke('recent:clear'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  confirm: (message, buttons) => ipcRenderer.invoke('confirm', { message, buttons }),
  alert: (message) => ipcRenderer.invoke('alert', message),
  readFile: (p) => ipcRenderer.invoke('read-file', p),
  readFileB64: (p) => ipcRenderer.invoke('read-file-b64', p),
  devWrite: (p, d) => ipcRenderer.invoke('dev:write', p, d),
  reveal: (p) => ipcRenderer.invoke('reveal', p),
  openExternal: (p) => ipcRenderer.invoke('openExternal', p),
  setDirty: (v) => ipcRenderer.send('set-dirty', v),
  setTitle: (t) => ipcRenderer.send('set-title', t),
  menuState: (st) => ipcRenderer.send('menu-state', st),
  quitNow: () => ipcRenderer.send('quit-now'),
  capture: (p) => ipcRenderer.invoke('dev:capture', p),
  recentInfo: () => ipcRenderer.invoke('recent:info'),
  installFontsWindows: () => ipcRenderer.invoke('fonts:installWindows'),
  pmConvertOld: (p) => ipcRenderer.invoke('pm:convertOld', p),
  indesignToIdml: (p) => ipcRenderer.invoke('indesign:toIdml', p),
  idmlWrite: (o) => ipcRenderer.invoke('idml:write', o),
  indesignSave: (o) => ipcRenderer.invoke('indesign:save', o),
  thumbCapture: (r) => ipcRenderer.invoke('thumb:capture', r),
  isMisspelled: (w) => { try { return webFrame.isWordMisspelled(w); } catch (_) { return false; } },
  suggestions: (w) => { try { return webFrame.getWordSuggestions(w); } catch (_) { return []; } },
  menuTemplate: () => ipcRenderer.invoke('menu:template'),
  onMenuTemplate: (fn) => ipcRenderer.on('menu-template', (_e, t) => fn(t)),
  menuRole: (role) => ipcRenderer.send('menu-role', role),
  chromeTheme: (t) => ipcRenderer.send('chrome-theme', t),
  platform: process.platform,
  onMenu: (fn) => ipcRenderer.on('menu', (_e, cmd, arg) => fn(cmd, arg)),
  onOpenFile: (fn) => ipcRenderer.on('open-file', (_e, data) => fn(data)),
});
